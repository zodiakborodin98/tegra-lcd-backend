# Generate a C header embedding a SPIR-V blob. Usage:
#   spv2header.py <in.spv> <out.h> <symbol>
import struct
import sys


def main() -> int:
    if len(sys.argv) != 4:
        sys.stderr.write("usage: spv2header.py <in.spv> <out.h> <symbol>\n")
        return 2
    spv, out, sym = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(spv, "rb") as f:
        data = f.read()
    if len(data) % 4 != 0:
        sys.stderr.write("spv2header: %s length %d not a multiple of 4\n" % (spv, len(data)))
        return 1
    lines = []
    lines.append("/* Auto-generated by scripts/spv2header.py from %s -- do not edit. */\n" % spv)
    lines.append("#ifndef TP_GEN_%s_H\n#define TP_GEN_%s_H\n" % (sym.upper(), sym.upper()))
    lines.append("#include <stdint.h>\n#include <stddef.h>\n")
    # Emit aligned uint32_t SPIR-V words: SPIR-V is little-endian, so unpack
    # each word explicitly rather than reinterpreting a uint8_t array.
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    lines.append("static const uint32_t %s[] = {\n" % sym)
    for i in range(0, len(words), 4):
        chunk = words[i:i + 4]
        lines.append("    " + " ".join("0x%08xU," % w for w in chunk) + "\n")
    lines.append("};\n")
    lines.append("static const size_t %s_size = sizeof(%s);\n" % (sym, sym))
    lines.append("#endif\n")
    with open(out, "w") as f:
        f.write("".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
